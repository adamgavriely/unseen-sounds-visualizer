"""Refresh the tagging tool (tagger/) for Adam's own tagging (30 Sept 2026): every listed clip must have at least 2
BEATs-detected sounds, and the page's suggestions come from BEATs alone (benchmark/gold/tagger_beats_suggest.py).

  - a listed clip with n_sounds < 2 leaves the tool: tagger/videos/dNNN.mp4 -> data/input/tagger_removed/ (kept, not
    deleted), unless Adam already has rows on it (KEEP_STARTED, from his last export);
  - new clips data/work/tagger_new/clips/nNNN.mp4 (web) and data/work/tagger_new/audioset/aNNN.mp4 (AudioSet-Strong,
    at most MAX_AUDIOSET), interleaved, n_sounds >= 2, are added as d101, d102, ... until the tool lists
    TARGET clips (new names, so nothing collides with what his browser saved under the old names); their source-map
    entries in tagger_new_sources.json get the new name as "tagger_clip";
  - tagger/src/clips.js and tagger/src/suggest.js are rewritten (suggestions = BEATs only).

    python benchmark/gold/tagger_refresh.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent.parent
TAGGER = _ROOT / "tagger"
BEATS = _ROOT / "benchmark" / "gold" / "tagger_beats_suggest.json"
NEW_DIR = _ROOT / "data" / "work" / "tagger_new" / "clips"
NEW_SRC = _ROOT / "benchmark" / "gold" / "tagger_new_sources.json"
AS_SRC = _ROOT / "benchmark" / "gold" / "tagger_audioset_sources.json"
AS_DIR = _ROOT / "data" / "work" / "tagger_new" / "audioset"
MAX_AUDIOSET = 50          # docs/tagger_selection_rule.md amendments 1 and 3: AudioSet-Strong only, 50 clips
REMOVED = _ROOT / "data" / "input" / "tagger_removed"
KEEP_STARTED = {"d002.mp4", "d081.mp4", "d084.mp4"}     # rows in tagger_AG_2026-09-29_2248.json, not done
TARGET = 100


def read_js(p: Path):
    t = p.read_text(encoding="utf-8")
    return json.loads(t[t.index("=") + 1: t.rindex(";")] if t.rstrip().endswith(";") else t[t.index("=") + 1:])


def main():
    beats = json.loads(BEATS.read_text(encoding="utf-8"))
    clips = read_js(TAGGER / "src" / "clips.js")
    keep, gone = [], []
    for c in clips:
        b = beats[c["id"]]
        (keep if b["n_sounds"] >= 2 or c["id"] in KEEP_STARTED else gone).append(c)
    REMOVED.mkdir(parents=True, exist_ok=True)
    for c in gone:
        shutil.move(str(TAGGER / "videos" / c["id"]), str(REMOVED / c["id"]))
    maps = {NEW_SRC: {}, AS_SRC: {}}
    for f in maps:
        if f.exists():
            maps[f] = json.loads(f.read_text(encoding="utf-8"))
    used = {v.get("tagger_clip") for m in maps.values() for v in m.values() if isinstance(v, dict)}
    nxt = 101
    web = []                                           # amendment 1: no web clips (was NEW_DIR n*.mp4)
    aset = sorted(AS_DIR.glob("a*.mp4"))[:MAX_AUDIOSET]
    mixed = []                                         # interleave, so the names do not reveal the source
    for i in range(max(len(web), len(aset))):
        mixed += ([web[i]] if i < len(web) else []) + ([aset[i]] if i < len(aset) else [])
    for p in mixed:
        if len(keep) >= TARGET:
            break
        src = maps[AS_SRC if p.parent == AS_DIR else NEW_SRC]
        if isinstance(src.get(p.name), dict) and src[p.name].get("tagger_clip"):
            continue
        b = beats.get(p.name)
        if not b or (p.parent != AS_DIR and b["n_sounds"] < 2):   # amendment 2: no BEATs rule for AudioSet clips
            continue
        while f"d{nxt:03d}.mp4" in used or (TAGGER / "videos" / f"d{nxt:03d}.mp4").exists():
            nxt += 1
        name = f"d{nxt:03d}.mp4"
        shutil.copy2(p, TAGGER / "videos" / name)
        beats[name] = b
        src.setdefault(p.name, {})["tagger_clip"] = name
        keep.append({"id": name, "src": "videos/" + name, "duration": b["duration"]})
        nxt += 1
    BEATS.write_text(json.dumps(beats, indent=1, ensure_ascii=False), encoding="utf-8")
    for f, m in maps.items():
        if m:
            f.write_text(json.dumps(m, indent=1, ensure_ascii=False), encoding="utf-8")
    (TAGGER / "src" / "clips.js").write_text("window.DELEGATION_CLIPS = " + json.dumps(keep) + ";\n", encoding="utf-8")
    lines = ["// Detector suggestions (benchmark/gold/tagger_beats_suggest.py: BEATs only, display bar). Generated by",
             "// benchmark/gold/tagger_refresh.py; do not edit by hand. Hidden in the tool until asked.",
             "window.DELEGATION_SUGGEST = {"]
    rows = []
    for c in keep:
        s = [{k: g[k] for k in ("label", "start", "end", "conf", "source")} for g in beats[c["id"]]["suggestions"]]
        if s:
            rows.append(json.dumps(c["id"]) + ": " + json.dumps(s, ensure_ascii=False))
    (TAGGER / "src" / "suggest.js").write_text("\n".join(lines) + "\n" + ",\n".join(rows) + "\n};\n", encoding="utf-8")
    print(f"kept {len(keep) - sum(1 for c in keep if int(c['id'][1:4]) > 100)} old, removed {len(gone)} "
          f"({', '.join(c['id'] for c in gone)}), added {sum(1 for c in keep if int(c['id'][1:4]) > 100)} new; "
          f"tool lists {len(keep)} clips")


if __name__ == "__main__":
    main()
