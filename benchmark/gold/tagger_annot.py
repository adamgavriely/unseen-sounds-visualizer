"""Other annotators' tags for the tagging tool (Adam, 2026-09-30): the AudioSet-Strong labels of the d101-d150 clips,
shown in tagger/ behind their own button ("Show other annotators' tags"), hidden until asked; the export records
annotators_shown_at and rows copied from them carry from_annotators: true.

Speech and music events are left out (they are not tagged in the tool); same-name events less than MERGE s apart are
joined into one row. Reads benchmark/gold/tagger_audioset_sources.json -> writes tagger/src/annot.js.

    python benchmark/gold/tagger_annot.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(_ROOT))
from src.labels import is_music, is_descendant  # noqa: E402

SRC = _ROOT / "benchmark" / "gold" / "tagger_audioset_sources.json"
OUT = _ROOT / "tagger" / "src" / "annot.js"
MERGE = 1.0
NOT_TAGGED = re.compile(r"(speech|speaking|conversation|narration|monologue|music|song|singing|choir|rapping|humming|yodel|chant|silence)", re.I)


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    out = {}
    for c in d["clips"]:
        name = (d.get(c["clip"] + ".mp4") or {}).get("tagger_clip")
        if not name:
            continue
        rows = []
        for e in sorted(c["strong_events"], key=lambda e: (e["name"], e["onset"])):
            n = e["name"]
            if NOT_TAGGED.search(n) or is_music(n) or is_descendant(n, "Speech") or is_descendant(n, "Music"):
                continue
            if rows and rows[-1]["label"] == n and e["onset"] - rows[-1]["end"] < MERGE:
                rows[-1]["end"] = max(rows[-1]["end"], round(e["offset"], 1))
            else:
                rows.append({"label": n, "start": round(e["onset"], 1), "end": round(e["offset"], 1), "source": "AudioSet-Strong"})
        rows.sort(key=lambda r: (r["start"], r["end"], r["label"]))
        if rows:
            out[name] = rows
    body = ",\n".join(json.dumps(k) + ": " + json.dumps(v, ensure_ascii=False) for k, v in sorted(out.items()))
    OUT.write_text("// Other annotators' tags (AudioSet-Strong labels). Generated by benchmark/gold/tagger_annot.py; do not edit\n"
                   "// by hand. Hidden in the tool until asked.\nwindow.DELEGATION_ANNOT = {\n" + body + "\n};\n", encoding="utf-8")
    print(f"{len(out)} clips, {sum(len(v) for v in out.values())} rows -> {OUT.relative_to(_ROOT)}")


if __name__ == "__main__":
    main()
